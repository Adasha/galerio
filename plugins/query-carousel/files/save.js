/**
 * src/save.js
 *
 * The Save function serialises the block's static markup to the post_content.
 *
 * All carousel configuration attributes are written as HTML data-* attributes
 * on the outermost wrapper element. The frontend view.js reads these at
 * runtime to configure the Embla Carousel instance — no wp_localize_script
 * or REST API calls are required.
 *
 * InnerBlocks.Content renders the serialised child core/query block.
 */

import { useBlockProps, InnerBlocks } from '@wordpress/block-editor';

/**
 * Serialise the block to its static HTML representation.
 *
 * WordPress calls this function when saving the post. The output is stored
 * in the database and served to visitors. It must be deterministic —
 * identical attributes must always produce identical markup — so that
 * WordPress can verify saved content hasn't been tampered with.
 *
 * @param {Object} props            Block props.
 * @param {Object} props.attributes Block attribute values.
 * @returns {JSX.Element}
 */
export default function save( { attributes } ) {
	const {
		transitionEffect,
		autoplay,
		autoplaySpeed,
		loop,
		slidesToScroll,
		showArrows,
		showDots,
	} = attributes;

	/**
	 * useBlockProps.save() automatically applies:
	 * - The block's primary CSS class (`wp-block-custom-query-carousel`)
	 * - Any additional className attribute set by the user
	 * - align classes (alignwide, alignfull)
	 * - spacing/color inline styles generated by block supports
	 *
	 * We merge our data-* attributes into this props object so WordPress
	 * block supports don't get dropped.
	 */
	const blockProps = useBlockProps.save( {
		// All carousel config attributes are serialised as data-* attributes.
		// Booleans are stored as the strings "true"/"false" so attribute
		// selectors can target them: [data-autoplay="true"].
		'data-transition-effect': transitionEffect,
		'data-autoplay': String( autoplay ),
		'data-autoplay-speed': String( autoplaySpeed ),
		'data-loop': String( loop ),
		'data-slides-to-scroll': String( slidesToScroll ),
		'data-show-arrows': String( showArrows ),
		'data-show-dots': String( showDots ),
	} );

	return (
		<div { ...blockProps }>
			{/*
			 * InnerBlocks.Content renders the serialised core/query block
			 * (and all of its own nested inner blocks) exactly as the editor
			 * saved them. No wrapper is added around them here because
			 * view.js targets the inner .wp-block-post-template element directly
			 * to wire it up as the Embla scroll container.
			 */}
			<InnerBlocks.Content />
		</div>
	);
}
